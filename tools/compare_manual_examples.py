#!/usr/bin/env python3
"""Compare guide-rs with native GUIDE on the GUIDE manual's examples.

The batch inputs in tests/fixtures/manual-examples were generated by
replaying the manual's (46.1) dialogs in the pinned 46.3 binary. The data
come from the manual's datafiles.zip, downloaded once into an ignored cache
and checked against a pinned hash. For each example the batch file is run
natively, translated into a guide-rs configuration, fitted with guide-rs and
compared row by row.

The unpruned mode rewrites each batch file to grow a tree without pruning, so
the comparison is exact. The pruned mode keeps the manual's cross-validation;
GUIDE draws its folds from its own random stream, so only sizes and broad
agreement compare.

Usage:
  python3 tools/compare_manual_examples.py --binary .reference/upstream/macos-arm64/guide
"""
import argparse
import csv
import hashlib
import io
import json
import math
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests/fixtures/manual-examples"
DATA_URL = "https://pages.stat.wisc.edu/~loh/treeprogs/guide/datafiles.zip"
DATA_SHA256 = "8e734235b9d25b4b19c50dab06b363153d5a94c7ef6de4d7e4bdb305e85b4e72"
CV_LINES = ("number of cross-validations", "mean-based CV tree", "SE number for pruning",
            "weighted error estimates during pruning")
FILE_SUFFIXES = (".txt", ".dsc", ".out", ".fit", ".tex", ".r", ".var", ".reg", ".coefs")


class Unsupported(Exception):
    """The example uses an option guide-rs does not implement."""


def parse_batch(text):
    """The header lines and the [value, annotation] entries of a batch file."""
    lines = text.splitlines()
    spec = []
    for line in lines[2:]:
        m = re.match(r'\s*("[^"]*"|\S+)\s*(?:\((.*)\))?\s*$', line)
        if m:
            spec.append([m.group(1).strip('"'), m.group(2) or ""])
    return "\n".join(lines[:2]) + "\n", spec


def get(spec, key, default=None):
    """The value of the first entry whose annotation contains `key`."""
    return next((v for v, a in spec if key in a), default)


def write_batch(header, spec):
    out = [header.rstrip("\n")]
    for v, a in spec:
        quoted = v.endswith(FILE_SUFFIXES) or " " in v
        out.append(f'"{v}"  ({a})' if quoted else f"{v}  ({a})")
    return "\n".join(out) + "\n"


def unpruned(spec):
    """`spec` growing an unpruned tree: no pruning code and no CV settings."""
    out = []
    for v, a in spec:
        if any(k in a for k in CV_LINES):
            continue
        if "prune by CV" in a:
            v = "3" if "3=no pruning" in a else "2"
        out.append([v, a])
    return out


def comparable(spec):
    """`spec` without options guide-rs does not reproduce for its node model.
    guide-rs truncates predictions only for multiple-linear leaves, so
    stepwise and polynomial examples are compared without truncation."""
    if get(spec, "0=stepwise, 1=multiple linear") in ("0", "2"):
        return [["0", a] if "0=no truncation" in a else [v, a] for v, a in spec]
    return spec


def parse_dsc(text):
    """Data file, missing code, first record line and (name, role) columns."""
    lines = [l for l in text.splitlines() if l.strip()]
    columns = []
    for line in lines[3:]:
        t = line.replace(",", " ").split()
        columns.append((t[1].strip('"'), t[2].lower()))
    return lines[0].strip().strip('"'), lines[1].strip().strip('"'), int(lines[2].split()[0]), columns


def periods(report):
    """Periods of P variables, from the native summary table."""
    return {m.group(1): float(m.group(2))
            for m in re.finditer(r"^\s+\d+\s+(\S+)\s+p\s+\S+\s+\S+\s+(\S+)", report, re.M)}


def translate(spec, columns, report, prune):
    """The guide-rs `data` and `fit` settings equivalent to a native run.

    `report` is the native output, which supplies GUIDE's data-dependent
    defaults (depth, minimum node size, periods, disabled interaction tests).
    Raises Unsupported for options guide-rs lacks.
    """
    classification = get(spec, "1=classification") == "1"
    node_kind = None
    if classification:
        node_kind = {"1": "constant", "4": "lda", "7": "lda_splits"}.get(
            get(spec, "1=simple, 2=nearest-neighbor"))
        if node_kind is None:
            raise Unsupported("classification node model")
    found = periods(report)
    data = {"target": None, "weight": None, "offset": None, "features": []}
    for k, (name, role) in enumerate(columns):
        if role == "d":
            data["target"] = name
        elif role == "w":
            data["weight"] = name
        elif role == "z":
            data["offset"] = name
        elif role == "e":
            raise Unsupported("E (estimated probability) variables")
        elif role in ("n", "s", "f"):
            r = {"n": "both", "s": "split", "f": "fit"}[role]
            if node_kind == "constant":
                r = "excluded" if role == "f" else "split"
            kind = ({"kind": "periodic", "period": found[name]} if name in found
                    else {"kind": "numeric"})
            data["features"].append({"name": name, "feature_type": kind, "role": r})
        elif role in ("c", "b", "i"):
            r = {"c": "split", "b": "both", "i": "fit"}[role]
            if classification:
                r = "split" if node_kind == "constant" else "both"
            data["features"].append({"name": name, "feature_type": {"kind": "categorical"},
                                     "role": r})
        elif role == "m":
            data["features"].append({"name": name, "feature_type": {"kind": "categorical"},
                                     "role": "flag", "flags": columns[k - 1][0]})
        elif role == "p":
            data["features"].append({"name": name,
                                     "feature_type": {"kind": "periodic", "period": found[name]},
                                     "role": "split"})
        else:
            data["features"].append({"name": name, "feature_type": {"kind": "categorical"},
                                     "role": "excluded"})
    fit = {"min_gain": 0.0}
    m = re.search(r"Maximum number of split levels: (\d+)", report)
    if m:
        fit["max_depth"] = int(m.group(1))
    m = re.search(r"Minimum node sample size: (\d+)", report)
    if m:
        fit["min_samples_leaf"] = int(m.group(1))
    if get(spec, "1=split point from quantiles") == "2":
        fit["max_split_candidates"] = 0
    if get(spec, "1=interaction tests") is not None:
        fit["interactions"] = get(spec, "1=interaction tests") == "1"
    order = get(spec, "0=linear 1st")
    if order is not None:
        fit["linear_splits"] = order in ("0", "1")
        fit["interactions"] = order != "3"
    if "No nodewise interaction tests" in report:
        fit["interactions"] = False
        fit["linear_splits"] = False
    if classification:
        fit["task"] = {"kind": "classification"}
        fit["node_model"] = {"kind": node_kind}
        if get(spec, "1=estimated priors") != "1":
            raise Unsupported("non-estimated priors")
    else:
        family = get(spec, "1=linear, 2=quantile")
        if family == "1":
            loss = {"kind": "squared_error"}
        elif family == "2" and get(spec, "1=one quantile") == "2":
            loss = {"kind": "dual_quantile", "lower": float(get(spec, "1st quantile probability")),
                    "upper": float(get(spec, "2nd quantile probability"))}
        elif family == "2":
            loss = {"kind": "quantile",
                    "probability": float(next(v for v, a in spec if a.strip() == "quantile"))}
        elif family == "3":
            loss = {"kind": "poisson"}
        elif family == "7":
            loss = {"kind": "logistic"}
        else:
            raise Unsupported(f"regression family {family}")
        fit["task"] = {"kind": "regression", "loss": loss}
        codes = ({"0": "stepwise", "1": "linear", "2": "polynomial", "3": "constant"}
                 if get(spec, "0=stepwise, 1=multiple linear") is not None
                 else {"1": "linear", "2": "polynomial", "3": "constant"})
        code = get(spec, "0=stepwise, 1=multiple linear") or get(
            spec, "1=multiple linear, 2=best simple polynomial")
        kind = codes.get(code)
        if kind is None:
            raise Unsupported(f"node model {code}")
        if kind == "polynomial":
            keep = get(spec, "1=drop insignificant powers", "1") == "2"
            fit["node_model"] = {"kind": "polynomial",
                                 "degree": int(get(spec, "highest degree of polynomial", 1)),
                                 "alpha": 1.0 if keep else float(get(spec, "significance level", 0.05))}
        elif kind == "stepwise":
            fit["node_model"] = {"kind": "stepwise", "alpha": 0.05, "max_variables": 0,
                                 "backward": False}
        else:
            fit["node_model"] = {"kind": kind}
        truncation = get(spec, "0=no truncation")
        if truncation is not None:
            fit["prediction_truncation"] = {"0": "none", "1": "node_range",
                                            "2": "node_range_expanded", "3": "global_range"}[truncation]
    if prune:
        fit["pruning"] = {"kind": "cross_validation",
                          "folds": int(get(spec, "number of cross-validations", 10)),
                          "standard_errors": float(get(spec, "SE number for pruning", 0.25))}
    else:
        fit["pruning"] = {"kind": "none"}
    return data, fit


def data_rows(text, data_file, missing, start):
    rows = []
    for line in text.splitlines()[start - 1:]:
        if line.strip():
            tokens = shlex.split(line.replace(",", " ") if data_file.endswith(".csv") else line)
            rows.append(["NA" if v == missing else v for v in tokens])
    return rows


def ensure_data(cache):
    """The manual's data files, downloaded once into `cache` and normalized:
    several files have CR CR LF line endings that GUIDE cannot read."""
    folder = cache / "datafiles"
    if folder.is_dir():
        return folder
    cache.mkdir(parents=True, exist_ok=True)
    archive = cache / "datafiles.zip"
    if not archive.exists():
        with urllib.request.urlopen(DATA_URL, timeout=120) as response:
            archive.write_bytes(response.read())
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    if digest != DATA_SHA256:
        raise SystemExit(f"datafiles.zip hash {digest} does not match the pinned {DATA_SHA256}")
    with zipfile.ZipFile(archive) as z:
        for member in z.namelist():
            name = Path(member)
            if member.endswith("/") or name.parts[0] != "datafiles" or name.name.startswith("._"):
                continue
            target = cache / member
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(z.read(member).replace(b"\r", b""))
    return folder


def run_example(name, native_binary, guide_rs, data_dir, prune, timeout):
    header, spec = parse_batch((FIXTURES / name / "input.txt").read_text())
    spec = comparable(spec if prune else unpruned(spec))
    with tempfile.TemporaryDirectory(prefix="guide-manual-") as temporary:
        work = Path(temporary)
        for f in data_dir.iterdir():
            shutil.copy(f, work / f.name)
        for entry in spec:
            if entry[1] == "name of output file":
                entry[0] = "native.out"
            elif entry[1].startswith("file name for fitted values"):
                entry[0] = "native.fit"
        (work / "batch.in").write_text(write_batch(header, spec))
        with open(work / "batch.in") as stdin:
            try:
                subprocess.run([str(native_binary)], stdin=stdin, cwd=work, capture_output=True,
                               timeout=timeout)
            except subprocess.TimeoutExpired:
                return {"example": name, "error": f"native run exceeded {timeout} s"}
        report = (work / "native.out").read_text() if (work / "native.out").exists() else ""
        if not (work / "native.fit").exists():
            return {"example": name, "error": "native run produced no fitted values"}
        data_file, missing, start, columns = parse_dsc(
            (work / get(spec, "name of DSC file")).read_text())
        try:
            data, fit = translate(spec, columns, report, prune)
        except Unsupported as e:
            return {"example": name, "unsupported": str(e)}
        rows = data_rows((work / data_file).read_text(), data_file, missing, start)
        names = [c for c, _ in columns]
        offset = names.index(data["offset"]) if data["offset"] else None
        if offset is not None:
            # GUIDE's Z variable is a log exposure; guide-rs takes the exposure.
            for r in rows:
                r[offset] = r[offset] if r[offset] == "NA" else repr(math.exp(float(r[offset])))
        buffer = io.StringIO()
        csv.writer(buffer).writerows([names] + rows)
        (work / "data.csv").write_text(buffer.getvalue())
        config = json.loads(subprocess.run([str(guide_rs), "config"], capture_output=True,
                                           text=True, check=True).stdout)
        config["data"].update(data)
        config["fit"].update(fit)
        (work / "config.json").write_text(json.dumps(config))
        for command in (["fit", "--data", "data.csv", "--config", "config.json", "--model", "model.json"],
                        ["predict", "--model", "model.json", "--data", "data.csv", "--output", "predictions.csv"]):
            try:
                p = subprocess.run([str(guide_rs), *command, "--force"], cwd=work,
                                   capture_output=True, text=True, timeout=timeout)
            except subprocess.TimeoutExpired:
                return {"example": name, "error": f"guide-rs {command[0]} exceeded {timeout} s"}
            if p.returncode:
                return {"example": name, "error": p.stderr.strip()[-300:]}
        native_rows = [shlex.split(l) for l in (work / "native.fit").read_text().splitlines()]
        # Two-quantile fits report a lower and an upper column, as guide-rs does.
        header_row = native_rows[0]
        native_columns = ([header_row.index("lowerquantile"), header_row.index("upperquantile")]
                          if "lowerquantile" in header_row else [header_row.index("predicted")])
        ours = list(csv.reader(io.StringIO((work / "predictions.csv").read_text())))[1:]
        model = json.loads((work / "model.json").read_text())

    def leaves(n):
        return 1 if n.get("split") is None else leaves(n["left"]) + leaves(n["right"])
    agree = total = 0
    classification = fit["task"]["kind"] == "classification"
    for native_row, our_row, row in zip(native_rows[1:], ours, rows):
        if native_row[0] != "y":
            continue
        total += 1
        same = True
        for column, mine in zip(native_columns, our_row):
            theirs, mine = native_row[column].strip('"'), mine.strip('"')
            if classification:
                same &= theirs == mine
            else:
                value = float(mine) / float(row[offset]) if offset is not None else float(mine)
                same &= abs(float(theirs) - value) <= 1e-4 * max(1.0, abs(float(theirs)))
        agree += same
    m = re.search(r"Number of terminal nodes of final tree: (\d+)", report)
    return {"example": name, "rows": total, "agree": agree,
            "native_leaves": int(m.group(1)) if m else None,
            "guide_rs_leaves": leaves(model["trees"][0]["root"])}


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--binary", type=Path, required=True, help="native GUIDE 46.3 executable")
    parser.add_argument("--guide-rs", type=Path, default=ROOT / "target/release/guide-rs")
    parser.add_argument("--cache", type=Path, default=ROOT / ".reference/manual-data")
    parser.add_argument("--mode", choices=["unpruned", "pruned", "both"], default="unpruned")
    parser.add_argument("--timeout", type=int, default=1800,
                        help="seconds allowed for each native or guide-rs run")
    parser.add_argument("--json", type=Path, help="also write the results to this file")
    parser.add_argument("examples", nargs="*", help="example names (default: all)")
    args = parser.parse_args()
    data_dir = ensure_data(args.cache)
    names = args.examples or sorted(p.name for p in FIXTURES.iterdir() if p.is_dir())
    modes = ["unpruned", "pruned"] if args.mode == "both" else [args.mode]
    results = []
    for mode in modes:
        for name in names:
            r = run_example(name, args.binary.resolve(), args.guide_rs.resolve(), data_dir,
                            mode == "pruned", args.timeout)
            r["mode"] = mode
            results.append(r)
            if "agree" in r:
                print(f"{mode:9} {name:28} {r['agree']:5}/{r['rows']:<5} rows agree; "
                      f"leaves native {r['native_leaves']}, guide-rs {r['guide_rs_leaves']}")
            else:
                print(f"{mode:9} {name:28} {r.get('unsupported') or r.get('error')}")
            sys.stdout.flush()
    if args.json:
        args.json.write_text(json.dumps(results, indent=2) + "\n")


if __name__ == "__main__":
    main()
